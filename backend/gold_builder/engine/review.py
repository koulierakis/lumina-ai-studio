async def run_self_review(
    job: Job, plan: Plan, project: Path, db,
    *,
    event_cb: Optional[Callable] = None,
) -> SelfReviewResult:
    context = build_review_context(job, plan, project)
    identity = _implementation_identity(job)
    prompt = (
        f"{context}\n\n"
        f"Review your own implementation against the request above. "
        f"Return STRICT JSON as specified."
    )
    req = CompletionRequest(
        messages=[Message(role="user", content=prompt)],
        system=SELF_REVIEW_SYSTEM,
        max_tokens=2000,
        temperature=0.1,
        json_mode=True,
    )
    result = SelfReviewResult(started_at=_now_iso(), provider=identity.get("provider"),
                              model=identity.get("model"), attempts=1)
    try:
        resp = await provider_router.complete(req, job_id=job.id, event_callback=event_cb)
        result.provider = resp.provider or result.provider
        result.model = resp.model or result.model
        parsed = parse_self_review(resp.text)
        parsed.provider = result.provider
        parsed.model = result.model
        parsed.attempts = 1
        result = parsed
    except Exception as exc:  # noqa: BLE001
        result.status = "needs_repair"
        result.malformed = True
        result.findings.append(ReviewFinding(
            severity="non_blocking", category="self_review_error", source="self",
            message=f"Self-review could not complete: {type(exc).__name__}",
        ))
    result.completed_at = _now_iso()
    return result


@dataclass
class IndependentOutcome:
    result: IndependentReviewResult
    candidates_tried: List[str]
    unavailable: bool = False
    unavailable_reason: Optional[str] = None
    external_exhaustion: bool = False
    cross_vendor: bool = False
    same_vendor_degraded: bool = False


async def run_independent_review(
    job: Job, plan: Plan, project: Path, db,
    *,
    event_cb: Optional[Callable] = None,
    reviewer_preferences: Optional[List[str]] = None,
) -> IndependentOutcome:
    """Run the independent reviewer with provider separation and fallback.

    Excludes the LATEST code-writing authority (which may be a repair provider,
    not only the original implementer). If the chosen reviewer fails, tries
    other independent providers. Only when there is genuinely no independent
    provider is the review marked unavailable (never a silent pass). In strict
    mode a cross-vendor reviewer is required unless the operator explicitly
    permits degraded same-vendor review.
    """
    # Exclude the authority of the last code write AND the original implementer:
    # a repair may have been authored by a different provider, but the bulk of the
    # code is still the implementer's, so neither may review this change.
    identity = current_code_author(job)
    original = _implementation_identity(job)
    strict = is_strict(job)
    # Exclude the latest code author (ordering base, always excluded) and the
    # original implementer: neither may review this change.
    candidates = provider_router.reviewer_candidates(
        identity, reviewer_preferences, exclude=[original],
    )
    # Prefer true cross-vendor separation over another model of the same vendor.
    cross = [p for p in candidates if provider_router.is_cross_vendor(p, identity)]
    same_vendor = [p for p in candidates if p not in cross]
    degraded = False
    if strict and not cross and same_vendor and not _allow_same_vendor_review():
        # Strict mode demands true vendor separation. Another model of the same
        # vendor is not accepted as equivalent independent authority unless the
        # operator explicitly opted into degraded same-vendor review.
        #
        # Distinguish a permanent gap (no cross-vendor authority is configured)
        # from a transient one (a cross-vendor authority exists but every such
        # provider is externally blocked/rate-limited right now). Both still fail
        # closed, but the transient case must be reported as an external
        # availability boundary so callers/tests can treat it as retryable.
        cross_vendor_cooling = any(
            provider_router.is_cross_vendor(p, identity)
            and (not p.available() or provider_router._cooldown_remaining(p.id) > 0)
            for p in provider_router.llm_providers()
        )
        if cross_vendor_cooling:
            reason = (
                "independent review unavailable: cross-vendor independent reviewer "
                "providers are externally blocked or rate-limited (auth/quota/rate limit)"
            )
        else:
            reason = (
                "no cross-vendor independent reviewer available for the latest code "
                "author (strict mode requires vendor separation)"
            )
        return IndependentOutcome(
            result=IndependentReviewResult(status="needs_repair", malformed=True),
            candidates_tried=[p.id for p in same_vendor], unavailable=True,
            unavailable_reason=reason, external_exhaustion=cross_vendor_cooling,
        )
    if cross:
        candidates = cross + same_vendor
    elif same_vendor:
        candidates = same_vendor
        degraded = True

    if not candidates:
        # An independent reviewer may exist but be externally blocked/cooling
        # (transient availability boundary), or there may be no independent
        # authority at all (a genuine review gap). Keep those distinct.
        exhausted = (
            provider_router.independent_review_externally_exhausted(identity)
            or provider_router.llm_externally_exhausted()
        )
        if exhausted:
            reason = (
                "independent review unavailable: independent reviewer providers are "
                "externally blocked or rate-limited (auth/quota/rate limit)"
            )
        elif identity.get("provider"):
            reason = "no healthy provider differs from the implementation authority"
        else:
            reason = "implementation provider identity could not be established"
        return IndependentOutcome(
            result=IndependentReviewResult(status="needs_repair", malformed=True),
            candidates_tried=[], unavailable=True, unavailable_reason=reason,
            external_exhaustion=exhausted,
        )

    context = build_review_context(job, plan, project)
    prompt = (
        f"{context}\n\n"
        f"Independently review this implementation. Find reasons it should NOT be "
        f"accepted. Return STRICT JSON as specified."
    )
    req = CompletionRequest(
        messages=[Message(role="user", content=prompt)],
        system=INDEPENDENT_REVIEW_SYSTEM,
        max_tokens=2500,
        temperature=0.1,
        json_mode=True,
    )

    tried: List[str] = []
    fallback_used = False
    external_boundary = False
    for provider in candidates:
        tried.append(provider.id)
        try:
            resp = await provider_router.complete_with_provider(
                req, provider, job_id=job.id, event_callback=event_cb,
            )
        except ProviderError as exc:
            fallback_used = True
            if exc.status_code in _EXTERNAL_BOUNDARY_STATUS_CODES:
                external_boundary = True
            continue
        except Exception:  # noqa: BLE001
            fallback_used = True
            continue
        parsed = parse_independent_review(resp.text)
        parsed.provider = resp.provider or provider.provider
        parsed.model = resp.model or provider.model
        parsed.attempts = 1
        parsed.fallback_used = fallback_used
        # A malformed response from one independent provider must not become an
        # approval. Try the next independent provider; if none works, it stays
        # needs_repair and the caller treats it as a blocker.
        if parsed.malformed and len(tried) < len(candidates):
            continue
        return IndependentOutcome(
            result=parsed, candidates_tried=tried,
            cross_vendor=provider_router.is_cross_vendor(provider, identity),
            same_vendor_degraded=degraded,
        )

    return IndependentOutcome(
        result=IndependentReviewResult(status="needs_repair", malformed=True,
                                       fallback_used=fallback_used),
        candidates_tried=tried,
        unavailable=True,
        unavailable_reason="all independent reviewer providers failed",
        external_exhaustion=(
            provider_router.independent_review_externally_exhausted(identity)
            or provider_router.llm_externally_exhausted()
            # Every reviewer we actually tried was rejected on an external
            # availability boundary (auth/quota/rate limit). A healthy provider
            # that is not an eligible reviewer (same vendor, or itself a code
            # author) must not make this look like a correctness failure.
            or external_boundary
        ),
        same_vendor_degraded=degraded,
    )


# --------------------------------------------------------------------------- repair

REVIEW_REPAIR_SYSTEM = """You are the repair layer of Gold Builder AI.
You receive a blocking review finding and must fix the root cause in ONE file.
Return the FULL corrected file contents only. No fences, no commentary.
Preserve all working behaviour and unrelated content."""


async def apply_review_repairs(
    job: Job, plan: Plan, project: Path, db,
    findings: Sequence[ReviewFinding],
    *,
    event_cb: Optional[Callable] = None,
    preferred_provider: Optional[str] = None,
    stage: str = "review_repair",
) -> List[str]:
    """Apply LLM repairs for blocking findings. Returns modified file paths.

    Repairs are written through the sandboxed workspace writer and validated for
    syntax before acceptance; an invalid repair is rejected, not written. Every
    accepted write updates the persisted code-author identity so the next
    independent reviewer cannot be the provider that authored this patch.
    """
    from .. import workspace
    from .generator import _strip_fences
    from .repair_policy import validate_source_syntax

    modified: List[str] = []
    target_findings = [f for f in findings if f.file]
    if not target_findings:
        target_findings = list(findings)

    for finding in target_findings[:6]:
        target = finding.file or (job.plan.entrypoints.get("main") if job.plan else None)
        if not target:
            continue
        existing = ""
        try:
            existing = workspace.safe_read_text(project, target)
        except FileNotFoundError:
            existing = ""
        except (OSError, ValueError):
            continue
        prompt = (
            f"ORIGINAL USER REQUEST:\n{job.request}\n\n"
            f"BLOCKING REVIEW FINDING ({finding.category}):\n{finding.message}\n"
            f"EVIDENCE:\n{finding.evidence or '(none)'}\n\n"
            f"FILE: {target}\n\n"
            f"CURRENT FILE CONTENTS:\n{existing or '(file does not exist)'}\n\n"
            f"Return the FULL corrected file contents only. Repair the root cause "
            f"comprehensively while preserving working behaviour."
        )
        req = CompletionRequest(
            messages=[Message(role="user", content=prompt)],
            system=REVIEW_REPAIR_SYSTEM,
            max_tokens=12000,
            temperature=0.15,
        )
        try:
            resp = await provider_router.complete(
                req, preferred_id=preferred_provider, job_id=job.id,
                event_callback=event_cb,
            )
        except ProviderError:
            continue
        content = _strip_fences(resp.text)
        syntax_err = validate_source_syntax(target, content)
        if syntax_err:
            continue
        workspace.safe_write(project, target, content)
        # The provider that produced this accepted patch is now the latest code
        # author; a reviewer must differ from it (not just the original implementer).
        record_code_author(job, resp.provider, resp.model, stage)
        from ..models import GeneratedFile
        replaced = False
        for idx, f in enumerate(job.files):
            if f.path == target:
                job.files[idx] = GeneratedFile(path=target, content=content)
                replaced = True
                break
        if not replaced:
            job.files.append(GeneratedFile(path=target, content=content))
        if target not in modified:
            modified.append(target)
    return modified


# --------------------------------------------------------------------------- verdicts

def deterministic_gates_ok(gates: Sequence[GateReport]) -> bool:
    from .quality_gates import all_passed
    return all_passed(list(gates))


def review_verdict(job: Job) -> str:
    """The review layer's verdict, independent of deterministic gates."""
    review = getattr(job, "review", None)
    if review is None:
        return "not_run"
    if review.unresolved_blockers:
        return "rejected"
    if review_is_stale(job):
        return "stale"
    if requires_independent_review(job) and review.independent_review_unavailable:
        return "approved" if _allow_missing_independent_review() else "unavailable"
    if review.self_review_status != "passed":
        return "not_run"
    if review.independent_review_status == "approved":
        return "approved"
    if review.independent_review_status == "rejected":
        return "rejected"
    if not requires_independent_review(job):
        return "approved"
    return "not_run"


def review_passed(job: Job) -> bool:
    """True only when the review layer completed without unresolved blockers.

    Self-review is mandatory and must be an EXPLICIT ``passed`` (never inferred
    from an empty blocker list). Independent review is required whenever policy
    demands it. A review approval is only valid for the code generation it
    inspected, so a write after approval makes it stale. Deterministic gates are
    checked separately by the orchestrator.
    """
    review = getattr(job, "review", None)
    if review is None:
        return False
    if review.unresolved_blockers:
        return False
    # A review approval never authorizes code that changed after it was given.
    if review_is_stale(job):
        return False
    # Self-review must have explicitly passed; an empty blocker list is not enough.
    if review.self_review_status != "passed":
        return False
    if requires_independent_review(job):
        if review.independent_review_unavailable:
            if not _allow_missing_independent_review():
                return False
        elif review.independent_review_status != "approved":
            return False
    return True


def _collect_blockers(
    self_review: Optional[SelfReviewResult],
    independent: Optional[IndependentReviewResult],
) -> List[ReviewFinding]:
    blockers: List[ReviewFinding] = []
    if self_review:
        blockers.extend(self_review.blocking_findings())
    if independent:
        blockers.extend(independent.blocking_findings)
    return blockers[:MAX_UNRESOLVED_RECORDED]


# --------------------------------------------------------------------------- pipeline

async def run_review_pipeline(
    job: Job,
    plan: Plan,
    project: Path,
    db,
    *,
    event_cb: Optional[Callable] = None,
    preferred_provider: Optional[str] = None,
    baseline_evidence=None,
    reuse_baseline_install: bool = False,
    changed_files: Optional[Sequence[str]] = None,
    failed_verification: bool = False,
    repaired: bool = False,
) -> ReviewEvidence:
    """Run the bounded review pipeline and persist evidence on ``job.review``.

    Returns the review evidence. The caller (orchestrator) must additionally
    require ``review_passed(job)`` and ``all_passed(job.gates)`` before
    COMPLETE. This function never sets a terminal job status itself.
    """
    from .checkpoint import save_job
    from ..models import LogEvent

    async def log(phase: str, message: str, level: str = "info", data: Optional[dict] = None):
        job.logs.append(LogEvent(phase=phase, message=message, level=level, data=data))
        job.updated_at = _now_iso()
        await save_job(db, job)

    review = job.review or ReviewEvidence()
    job.review = review

    # Resume safety: a job recovered during review must not duplicate an
    # already-completed reviewer/repair pass. When the pipeline already
    # concluded, re-evaluate the persisted verdict without any provider call.
    # A concluded review whose approval is now STALE (code changed after it) is
    # not reused: the current generation must be re-reviewed.
    if review.review_completed_at and not review_is_stale(job):
        return review
    if review.review_completed_at and review_is_stale(job):
        review.review_completed_at = None

    if not review.review_started_at:
        review.review_started_at = _now_iso()
    review.strict = is_strict(job)
    review.required = requires_independent_review(job)
    review.max_self_review_repairs = max(0, int(getattr(job, "max_self_review_repairs", 2)))
    review.max_independent_review_repairs = max(0, int(getattr(job, "max_independent_review_repairs", 2)))
    identity = _implementation_identity(job)
    review.implementation_provider = review.implementation_provider or identity.get("provider")
    review.implementation_model = review.implementation_model or identity.get("model")

    await log(
        "review",
        f"Self-reviewing implementation (implementer={review.implementation_provider or 'unknown'})",
        data={"event": "SELF REVIEW START", "strict": review.strict,
              "implementation_provider": review.implementation_provider},
    )

    max_cycles = max(review.max_self_review_repairs, review.max_independent_review_repairs) + 1
    approved = False
    # A recovered run reuses a completed self-review that produced no blockers
    # and a completed independent approval, so a reviewer is never run twice for
    # the same generation.
    reuse_self = bool(review.self_review is not None
                      and review.review_attempt_count > 0
                      and review.self_review.status == "pass"
                      and not review.self_review.blocking_findings()
                      and review.self_review_generation == review.code_generation)
    reuse_independent = bool(review.independent_review is not None
                             and review.independent_review_status == "approved"
                             and not review.unresolved_blockers
                             and review.independent_review_generation == review.code_generation)

    for _cycle in range(max_cycles):
        # ---- SELF REVIEW ----
        transition(job, JobStatus.SELF_REVIEWING, context="review:self")
        if reuse_self and review.self_review is not None:
            self_result = review.self_review
            await log("review", "Reusing completed self-review after recovery",
                      data={"event": "SELF REVIEW COMPLETE", "reused": True})
        else:
            review.review_attempt_count += 1
            self_result = await run_self_review(job, plan, project, db, event_cb=event_cb)
            review.self_review = self_result
            review.self_review_generation = review.code_generation
            # Persist the fail-closed status BEFORE any repair so a restart
            # during repair cannot reuse a needs_repair self-review as passed.
            review.self_review_status = _self_status(self_result)
            review.self_review_findings = list(self_result.findings)
            await log(
                "review",
                f"Self-review {self_result.status} (confidence={self_result.confidence})",
                data={"event": "SELF REVIEW COMPLETE", "status": self_result.status,
                      "findings": [f.model_dump() for f in self_result.findings],
                      "attempt": review.review_attempt_count},
            )
        reuse_self = False

        self_blockers = self_result.blocking_findings()
        # Self-review must be an EXPLICIT "pass" with no blocking finding. Any
        # other status is a blocker even when the model forgot to mark a finding
        # as blocking: needs_repair, fail, malformed, or pass+blocking all block.
        # Never infer approval from an empty findings list.
        if self_result.status != "pass" or self_result.malformed:
            if self_result.malformed:
                category, message = (
                    "malformed_self_review",
                    "Self-review returned malformed output; not treated as a pass",
                )
            elif self_result.status == "fail":
                category, message = ("self_review_failed", "Self-review reported failure")
            else:
                category, message = (
                    "self_review_needs_repair",
                    f"Self-review status '{self_result.status}' is not an explicit pass",
                )
            if not any(f.category == category for f in self_blockers):
                self_blockers = list(self_blockers) + [ReviewFinding(
                    severity="blocking", category=category, source="self", message=message,
                )]
        if self_blockers:
            if review.self_repair_count >= review.max_self_review_repairs:
                # Self-review found a blocking issue and the repair budget is
                # exhausted: fail loudly rather than proceeding.
                review.unresolved_blockers = self_blockers
                review.review_completed_at = _now_iso()
                await _emit_blocker(log, self_blockers, source="self")
                await save_job(db, job)
                return review
            review.self_repair_count += 1
            review.repair_attempt_count += 1
            await _emit_blocker(log, self_blockers, source="self")
            transition(job, JobStatus.REVIEW_REPAIR, context="review:self_repair")
            await log("review", "Repairing review finding (self-review)",
                      data={"event": "REVIEW REPAIR START", "source": "self",
                            "count": review.repair_attempt_count})
            modified = await apply_review_repairs(
                job, plan, project, db, self_blockers, event_cb=event_cb,
                preferred_provider=preferred_provider, stage="self_review_repair",
            )
            await log("review", f"Review repair modified {len(modified)} file(s)",
                      data={"event": "REVIEW REPAIR COMPLETE", "files": modified,
                            "code_generation": review.code_generation,
                            "code_author": review.last_code_author_provider})
            await _final_verify(job, plan, project, db, log,
                                preferred_provider, baseline_evidence,
                                reuse_baseline_install)
            continue

        # ---- INDEPENDENT REVIEW ----
        if requires_independent_review(job):
            transition(job, JobStatus.INDEPENDENT_REVIEW, context="review:independent")
            if reuse_independent and review.independent_review is not None:
                outcome = IndependentOutcome(
                    result=review.independent_review,
                    candidates_tried=[review.reviewer_provider or ""],
                )
                await log("review", "Reusing completed independent review after recovery",
                          data={"event": "INDEPENDENT REVIEW COMPLETE", "reused": True})
            else:
                await log(
                    "review", "Independent review starting",
                    data={"event": "INDEPENDENT REVIEW START",
                          "exclude": review.implementation_provider},
                )
                outcome = await run_independent_review(job, plan, project, db, event_cb=event_cb)
            reuse_independent = False
            review.independent_review = outcome.result
            review.reviewer_provider = outcome.result.provider
            review.reviewer_model = outcome.result.model
            review.independent_review_status = _independent_status(outcome.result)
            review.independent_review_findings = list(outcome.result.all_findings())
            review.independent_review_unavailable = outcome.unavailable
            review.unavailable_reason = outcome.unavailable_reason
            review.external_provider_exhaustion = outcome.external_exhaustion
            review.cross_vendor_review = outcome.cross_vendor
            review.same_vendor_degraded = outcome.same_vendor_degraded
            review.independent_review_generation = review.code_generation
            await log(
                "review",
                f"Independent review — {review.reviewer_provider or 'unavailable'}: "
                f"{outcome.result.status}",
                data={"event": "INDEPENDENT REVIEW COMPLETE",
                      "status": outcome.result.status,
                      "provider": review.reviewer_provider,
                      "model": review.reviewer_model,
                      "tried": outcome.candidates_tried,
                      "unavailable": outcome.unavailable,
                      "cross_vendor": outcome.cross_vendor,
                      "same_vendor_degraded": outcome.same_vendor_degraded,
                      "findings": [f.model_dump() for f in outcome.result.all_findings()]},
            )
            if outcome.unavailable:
                await log(
                    "review",
                    "Independent review unavailable"
                    + (" (required: failing closed)" if requires_independent_review(job)
                       else " (recorded explicitly; not treated as a pass)"),
                    level="error",
                    data={"event": "REVIEW BLOCKER FOUND", "reason": outcome.unavailable_reason},
                )
                if requires_independent_review(job):
                    if _allow_missing_independent_review():
                        # Explicit deployment policy: record the unavailability
                        # loudly but continue. Never a silent pass.
                        review.unresolved_blockers = []
                        approved = True
                        await save_job(db, job)
                        break
                    if outcome.external_exhaustion:
                        # Every configured provider is externally blocked or
                        # rate-limited. This is a live availability boundary, not
                        # a correctness signal; fail closed with a distinct,
                        # operator-actionable reason (never a silent pass).
                        review.unresolved_blockers = [
                            ReviewFinding(
                                severity="blocking",
                                category="external_provider_exhaustion",
                                source="independent",
                                message=(
                                    "independent review unavailable: configured live "
                                    "providers are externally blocked or rate-limited"
                                ),
                            )
                        ]
                        review.review_completed_at = _now_iso()
                        await save_job(db, job)
                        return review
                    # Policy demands independent review: fail closed.
                    review.unresolved_blockers = [
                        ReviewFinding(
                            severity="blocking", category="independent_review_unavailable",
                            source="independent",
                            message=outcome.unavailable_reason or "independent review unavailable",
                        )
                    ]
                    review.review_completed_at = _now_iso()
                    await save_job(db, job)
                    return review
                # Non-strict policy allows continuing, but the unavailability is
                # persisted so it is never silently mistaken for an approval.
                approved = True
                review.unresolved_blockers = []
                break

            independent_blockers = list(outcome.result.blocking_findings)
            for req_id in outcome.result.requirements_with_insufficient_evidence:
                independent_blockers.append(ReviewFinding(
                    severity="blocking", category="insufficient_evidence",
                    requirement_id=req_id, source="independent",
                    message=f"Reviewer could not substantiate requirement {req_id}",
                ))
            if outcome.result.malformed:
                independent_blockers.append(ReviewFinding(
                    severity="blocking", category="malformed_review", source="independent",
                    message="Reviewer returned malformed output; not treated as approval",
                ))

            # An AI approval cannot stand against a deterministic failure.
            await _final_verify(job, plan, project, db, log,
                                preferred_provider, baseline_evidence,
                                reuse_baseline_install)
            if not deterministic_gates_ok(job.gates):
                independent_blockers.extend(_gate_blockers(job.gates))

            if independent_blockers:
                await _emit_blocker(log, independent_blockers, source="independent")
                if review.independent_repair_count < review.max_independent_review_repairs:
                    review.independent_repair_count += 1
                    review.repair_attempt_count += 1
                    transition(job, JobStatus.REVIEW_REPAIR, context="review:independent_repair")
                    await log("review", "Repairing review finding",
                              data={"event": "REVIEW REPAIR START", "source": "independent",
                                    "count": review.repair_attempt_count})
                    modified = await apply_review_repairs(
                        job, plan, project, db, independent_blockers, event_cb=event_cb,
                        preferred_provider=preferred_provider,
                        stage="independent_review_repair",
                    )
                    await log("review", f"Review repair modified {len(modified)} file(s)",
                              data={"event": "REVIEW REPAIR COMPLETE", "files": modified,
                                    "code_generation": review.code_generation,
                                    "code_author": review.last_code_author_provider})
                    continue
                review.unresolved_blockers = independent_blockers
                review.review_completed_at = _now_iso()
                await save_job(db, job)
                return review

            approved = True
            review.unresolved_blockers = []
            break

        # Non-strict, independent review not required: self-review only.
        approved = True
        review.unresolved_blockers = []
        break

    review.last_deterministic_gates_passed = deterministic_gates_ok(job.gates)
    review.review_completed_at = _now_iso()
    if approved and review.self_review_status == "passed":
        # The approval is valid only for the code generation it inspected.
        review.reviewed_generation = review.code_generation
    if approved:
        await log(
            "review",
            "Final review passed"
            + (f" (independent reviewer {review.reviewer_provider})"
               if review.reviewer_provider else ""),
            data={"event": "FINAL REVIEW PASSED", "review_attempts": review.review_attempt_count,
                  "repair_attempts": review.repair_attempt_count,
                  "code_generation": review.code_generation,
                  "reviewed_generation": review.reviewed_generation},
        )
    await save_job(db, job)
    return review


async def _final_verify(
    job: Job, plan: Plan, project: Path, db, log,
    preferred_provider: Optional[str] = None,
    baseline_evidence=None,
    reuse_baseline_install: bool = False,
) -> None:
    """Re-run the canonical deterministic build + browser verification.

    Delegates to the orchestrator's gate pipeline so baseline handling, browser
    evidence requirements and gate evaluation stay identical to the rest of the
    engine. AI review never replaces this step.
    """
    from .orchestrator import _build_and_verify_with_gates

    transition(job, JobStatus.FINAL_VERIFYING, context="review:final_verify")
    await log("review", "Re-running deterministic build/tests/browser verification",
              data={"event": "FINAL VERIFY START"})
    await _build_and_verify_with_gates(
        job, plan, project, workspace_artifacts(job), db, preferred_provider,
        baseline_evidence=baseline_evidence,
        reuse_baseline_install=reuse_baseline_install,
    )
    await log(
        "review",
        f"Final deterministic verification: gates_passed={deterministic_gates_ok(job.gates)}",
        data={"event": "FINAL VERIFY", "gates": _gates_summary(job.gates)},
    )


def workspace_artifacts(job: Job) -> Path:
    from .. import workspace
    return workspace.artifacts_dir(job.id)


def _self_status(result: SelfReviewResult) -> str:
    if result.status == "pass" and not result.blocking_findings():
        return "passed"
    if result.blocking_findings():
        return "repair_requested"
    if result.status == "fail":
        return "failed"
    return "repair_requested"


def _independent_status(result: IndependentReviewResult) -> str:
    if result.malformed:
        return "malformed"
    if result.status == "approve":
        return "approved"
    if result.status == "reject":
        return "rejected"
    return "needs_repair"


def _gate_blockers(gates: Sequence[GateReport]) -> List[ReviewFinding]:
    blockers: List[ReviewFinding] = []
    for g in gates:
        if g.enabled and str(g.status).upper() == "FAIL":
            blockers.append(ReviewFinding(
                severity="blocking", category="deterministic_gate", source="deterministic",
                message=f"Deterministic gate failed: {g.name}",
                evidence=_truncate(g.detail, 800) if g.detail else None,
            ))
    if not blockers:
        blockers.append(ReviewFinding(
            severity="blocking", category="deterministic_gate", source="deterministic",
            message="Deterministic verification did not pass",
        ))
    return blockers


async def _emit_blocker(log, findings: Sequence[ReviewFinding], *, source: str) -> None:
    for f in findings[:10]:
        await log(
            "review",
            f"Blocking issue ({source}): {f.message[:180]}",
            level="warn",
            data={"event": "REVIEW BLOCKER FOUND", "source": source,
                  "severity": f.severity, "category": f.category,
                  "file": f.file, "requirement_id": f.requirement_id},
        )
