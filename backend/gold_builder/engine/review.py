def is_strict(job: Job) -> bool:
    """Whether strict review is active for this job (persisted flag wins)."""
    return bool(getattr(job, "strict_review", False))


def requires_independent_review(job: Job) -> bool:
    """Independent review is mandatory in strict mode or when explicitly set."""
    return bool(
        getattr(job, "strict_review", False)
        or getattr(job, "require_independent_review", False)
    )


def _allow_missing_independent_review() -> bool:
    """Deployment policy for continuing without an independent reviewer.

    Defaults to fail-closed. An operator may explicitly opt in to a documented
    degraded mode with ``GB_ALLOW_MISSING_INDEPENDENT_REVIEW=1``; even then the
    unavailability is persisted and surfaced, never silently treated as a pass.
    """
    return os.environ.get("GB_ALLOW_MISSING_INDEPENDENT_REVIEW", "").strip().lower() in {
        "1", "true", "yes", "on",
    }


def derive_strict_review(
    *,
    mode: str = "new",
    plan: Optional[Plan] = None,
    changed_files: Optional[Sequence[str]] = None,
    request: str = "",
    failed_verification: bool = False,
    repaired: bool = False,
    explicit: Optional[bool] = None,
) -> tuple[bool, List[str]]:
    """Deterministically decide strict-review activation and its reasons.

    Strict review activates automatically for existing-repo changes, multi-file
    changes, backend/state/persistence changes, security/auth/payment/database/
    concurrency work, large diffs, and jobs whose verification failed or was
    repaired.
    """
    reasons: List[str] = []
    files = [str(f) for f in (changed_files or [])]
    if mode == "existing-repo":
        reasons.append("existing-repo change")
    if len(files) > 1:
        reasons.append("multi-file change")
    if failed_verification:
        reasons.append("failed or repaired verification")
    if repaired:
        reasons.append("job required repair")

    haystack = " ".join([request or "", " ".join(files)]).lower()
    keyword_groups = {
        "authentication/security": (
            "auth", "login", "signin", "sign-in", "password", "token", "secret",
            "security", "permission", "oauth", "jwt", "session", "credential",
        ),
        "payments": ("payment", "checkout", "billing", "stripe", "invoice", "price"),
        "database migration": ("migration", "migrate", "schema", "alembic", "flyway"),
        "concurrency": ("concurrency", "concurrent", "race", "lock", "mutex", "thread", "async"),
        "backend/state/persistence": (
            "persist", "localstorage", "database", "backend", "api/", "server",
            "state", "storage", "indexeddb",
        ),
    }
    for label, words in keyword_groups.items():
        if any(word in haystack for word in words):
            reasons.append(label)
            break

    large = False
    for f in files:
        if f.endswith((".py", ".ts", ".tsx", ".js", ".jsx", ".go", ".rb", ".java", ".sql")):
            large = True
            break
    if large and len(files) >= 3:
        reasons.append("large diff")

    auto = bool(reasons)
    if explicit is None:
        return auto, reasons
    return bool(explicit), (reasons if explicit else [])


# --------------------------------------------------------------------------- helpers

def _now_iso() -> str:
    return datetime.now(timezone.utc).isoformat()


def _truncate(value: Optional[str], limit: int) -> str:
    text = value or ""
    if len(text) <= limit:
        return text
    return text[:limit] + "\n[... truncated for review context ...]"


def _implementation_identity(job: Job) -> Dict[str, Any]:
    """Best-known identity of the implementation authority.

    Prefers the persisted review evidence (restart-safe) and falls back to the
    router's in-memory last-success record.
    """
    review = getattr(job, "review", None)
    if review and review.implementation_provider:
        return {
            "provider": review.implementation_provider,
            "model": review.implementation_model or "",
        }
    remembered = provider_router.last_success_for(job.id)
    if remembered:
        return {
            "provider": remembered.get("provider", ""),
            "model": remembered.get("model", ""),
        }
    cfg = job.provider_config or {}
    configured = cfg.get("llm_provider")
    if configured:
        known = provider_router.provider_identity_for(configured)
        if known:
            return {"provider": known["provider"], "model": known["model"]}
    return {"provider": "", "model": ""}


def _changed_files(job: Job, project: Path) -> List[str]:
    paths: List[str] = []
    if job.repo_changes is not None:
        paths.extend(job.repo_changes.created)
        paths.extend(job.repo_changes.modified)
        paths.extend(job.repo_changes.deleted)
    paths.extend(f.path for f in job.files)
    seen: set[str] = set()
    ordered: List[str] = []
    for p in paths:
        if p and p not in seen:
            seen.add(p)
            ordered.append(p)
    return ordered


def _file_context(project: Path, paths: Sequence[str]) -> str:
    from .. import workspace

    blocks: List[str] = []
    for rel in list(paths)[:MAX_CONTEXT_FILES]:
        target = project / rel
        if not target.is_file():
            blocks.append(f"--- {rel} --- (deleted or not on disk)")
            continue
        try:
            content = workspace.safe_read_text(project, rel)
        except (FileNotFoundError, OSError, ValueError):
            blocks.append(f"--- {rel} --- (unreadable)")
            continue
        blocks.append(f"--- {rel} ---\n{_truncate(content, MAX_FILE_CHARS)}")
    return "\n\n".join(blocks)


def _diff_context(job: Job, project: Path, paths: Sequence[str]) -> str:
    import difflib

    lines: List[str] = []
    for rel in list(paths)[:MAX_CONTEXT_FILES]:
        generated = next((f for f in job.files if f.path == rel), None)
        current = ""
        target = project / rel
        if target.is_file():
            try:
                current = target.read_text(encoding="utf-8", errors="replace")
            except OSError:
                current = ""
        original = generated.content if generated else ""
        if original == current:
            continue
        lines.extend(difflib.unified_diff(
            original.splitlines(), current.splitlines(),
            fromfile=f"a/{rel}", tofile=f"b/{rel}", lineterm="",
        ))
        lines.append("")
    return "\n".join(lines)


def _build_evidence_summary(job: Job) -> Dict[str, Any]:
    ev = job.build_evidence
    summary: Dict[str, Any] = {}
    if ev is not None:
        for name in ("install", "build", "typecheck", "lint", "test"):
            results = getattr(ev, name, []) or []
            if results:
                summary[name] = {
                    "rc": results[-1].rc,
                    "tail": _truncate(results[-1].output_tail, 1500),
                }
    return summary


def _verification_summary(job: Job) -> Dict[str, Any]:
    v = job.verification
    if v is None:
        return {}
    return {
        "passed": v.passed,
        "http_status": v.http_status,
        "console_errors": v.console_errors[:10],
        "network_errors": v.network_errors[:10],
        "page_errors": v.page_errors[:10],
        "semantic_required": v.semantic_required,
        "semantic_passed": v.semantic_passed,
        "browser_executed": bool((v.details or {}).get("browser_executed")),
        "failed_steps": [
            {"action": s.action, "error": s.error}
            for s in (v.steps or []) if not s.ok
        ][:10],
    }


def _gates_summary(gates: Sequence[GateReport]) -> List[Dict[str, Any]]:
    return [
        {"name": g.name, "enabled": g.enabled, "status": g.status, "blocking": g.blocking}
        for g in gates
    ]


def _execution_logs_summary(job: Job, limit: int = 40) -> List[Dict[str, Any]]:
    """Compact tail of the activity stream so reviewers can see execution order."""
    logs = getattr(job, "logs", None) or []
    tail = logs[-limit:]
    return [
        {"phase": getattr(entry, "phase", ""), "level": getattr(entry, "level", "info"),
         "message": _truncate(str(getattr(entry, "message", "")), 400)}
        for entry in tail
    ]


def _self_review_reference(job: Job) -> Optional[Dict[str, Any]]:
    """The implementer's own conclusions, clearly marked as advisory reference.

    The independent reviewer receives these so it can deliberately try to
    disprove them, never to inherit them.
    """
    review = getattr(job, "review", None)
    result = getattr(review, "self_review", None) if review else None
    if result is None:
        return None
    return {
        "advisory_only": True,
        "status": result.status,
        "confidence": result.confidence,
        "findings": [f.model_dump() for f in result.findings],
        "recommended_repairs": result.recommended_repairs,
    }


def build_review_context(job: Job, plan: Plan, project: Path) -> str:
    """Deterministic review context shared by both review passes."""
    paths = _changed_files(job, project)
    requirements = [
        {"id": r.id, "text": r.text, "kind": r.kind, "verifiable": r.verifiable}
        for r in plan.requirements
    ]
    scenario = [{"action": s.action, "args": s.args, "requirement_id": s.requirement_id}
                for s in plan.verification_scenario]
    payload = {
        "original_user_request": job.request,
        "mode": job.mode,
        "stack_id": plan.stack_id,
        "plan_description": plan.description,
        "requirements": requirements,
        "acceptance_contract": scenario,
        "changed_files": paths,
        "build_evidence": _build_evidence_summary(job),
        "verification": _verification_summary(job),
        "gates": _gates_summary(job.gates),
        "execution_logs": _execution_logs_summary(job),
        "self_review": _self_review_reference(job),
    }
    header = "REVIEW CONTEXT (authoritative, deterministic):\n" + json.dumps(
        payload, indent=2, default=str,
    )
    diff = _diff_context(job, project, paths)
    files = _file_context(project, paths)
    sections = [header]
    if diff:
        sections.append("UNIFIED DIFF (generated -> on disk):\n" + _truncate(diff, MAX_DIFF_CHARS))
    sections.append("CHANGED FILE CONTENTS:\n" + files)
    return "\n\n".join(sections)


