def _allow_same_vendor_review() -> bool:
    """Operator opt-in for degraded same-vendor independent review in strict mode."""
    return str(os.environ.get("GB_ALLOW_SAME_VENDOR_REVIEW", "")).strip().lower() in {
        "1", "true", "yes", "on",
    }


def record_code_author(
    job: Job,
    provider: Optional[str],
    model: Optional[str],
    stage: str,
) -> None:
    """Persist the authority of the latest code-writing change and bump generation.

    Called after every successful LLM-generated write (generation or any repair
    stage). Incrementing ``code_generation`` invalidates any earlier review
    approval, which was only ever valid for the code it inspected.
    """
    review = getattr(job, "review", None)
    if review is None:
        review = ReviewEvidence()
        job.review = review
    review.last_code_author_provider = provider or review.last_code_author_provider
    review.last_code_author_model = model or review.last_code_author_model
    review.last_code_author_stage = stage
    review.last_code_author_at = _now_iso()
    review.code_generation = int(review.code_generation or 0) + 1


def record_code_author_from_router(job: Job, stage: str) -> None:
    """Record the code author using the router's last-success record.

    Used by the orchestrator at write sites where the LLM response object is not
    threaded through; the router records the provider that actually served the
    most recent request for this job.
    """
    remembered = provider_router.last_success_for(job.id) or {}
    record_code_author(
        job, remembered.get("provider"), remembered.get("model"), stage,
    )


def current_code_author(job: Job) -> Dict[str, Any]:
    """The authority that most recently wrote code, preferring persisted evidence.

    Falls back to the original implementation identity for legacy jobs whose
    code was never re-written after the review layer was introduced.
    """
    review = getattr(job, "review", None)
    if review and (review.last_code_author_provider or review.last_code_author_model):
        return {
            "provider": review.last_code_author_provider or "",
            "model": review.last_code_author_model or "",
        }
    return _implementation_identity(job)


def review_is_stale(job: Job) -> bool:
    """True when code changed after the review approval that would authorize it.

    Only meaningful for an approved review: a review that already ended with
    unresolved blockers is *failed*, not stale, so this returns False there.
    """
    review = getattr(job, "review", None)
    if review is None:
        return False
    if review.unresolved_blockers:
        return False
    if not review.review_completed_at:
        return False
    return int(review.code_generation or 0) != int(review.reviewed_generation or 0)


