"""Mandatory self-review + independent-AI-review layer.

Gold Builder must never treat its own generated work as complete immediately
after implementation. This module adds a bounded, evidence-driven review
pipeline:

    BUILD -> SELF REVIEW -> INDEPENDENT AI REVIEW -> DETERMINISTIC VERIFICATION
          -> REPAIR IF NEEDED -> RE-REVIEW -> FINAL VERIFY -> COMPLETE

Design rules enforced here:

* Self-review is advisory: it can request a repair but can never mark a job
  COMPLETE on its own.
* Independent review uses a provider/model that differs from the implementer.
  The same authority that produced the implementation is never the sole
  decider of its correctness.
* AI approval is never sufficient: deterministic gates remain the final
  authority (``all_passed`` on the freshly evaluated gates).
* Malformed reviewer output is treated as "needs repair", never as approval.
* Strict mode fails closed when no independent provider is available.
* Repair loops are bounded; exhaustion fails loudly with unresolved blockers.

All decisions are deterministic given persisted job state + provider responses.
"""
