def _extract_json(text: str) -> Optional[dict]:
    if not isinstance(text, str):
        return None
    stripped = text.strip()
    fenced = re.match(r"```(?:json)?\s*(.*?)```", stripped, re.DOTALL)
    if fenced:
        stripped = fenced.group(1).strip()
    start = stripped.find("{")
    if start < 0:
        return None
    depth = 0
    for i in range(start, len(stripped)):
        c = stripped[i]
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                try:
                    data = json.loads(stripped[start:i + 1])
                except (ValueError, TypeError):
                    return None
                return data if isinstance(data, dict) else None
    return None


def _normalise_finding(raw: Any, *, default_severity: str = "non_blocking",
                       source: str = "") -> Optional[ReviewFinding]:
    if isinstance(raw, str):
        raw = {"message": raw}
    if not isinstance(raw, dict):
        return None
    severity = str(raw.get("severity") or default_severity).strip().lower()
    if severity in {"blocking", "blocker", "critical", "high", "error", "fail", "failed"}:
        severity = "blocking"
    else:
        severity = "non_blocking"
    message = str(raw.get("message") or raw.get("finding") or raw.get("description") or "").strip()
    if not message:
        return None
    return ReviewFinding(
        severity=severity,
        category=str(raw.get("category") or "other").strip()[:80],
        requirement_id=(str(raw["requirement_id"]) if raw.get("requirement_id") else None),
        file=(str(raw["file"]) if raw.get("file") else None),
        message=message[:2000],
        evidence=(_truncate(str(raw["evidence"]), 1500) if raw.get("evidence") else None),
        source=source,
    )


def _normalise_finding_list(raw: Any, *, default_severity: str, source: str) -> List[ReviewFinding]:
    if not raw:
        return []
    if isinstance(raw, dict):
        raw = [raw]
    if not isinstance(raw, list):
        return []
    findings: List[ReviewFinding] = []
    for item in raw:
        finding = _normalise_finding(item, default_severity=default_severity, source=source)
        if finding is not None:
            findings.append(finding)
    return findings


def parse_self_review(text: str) -> SelfReviewResult:
    """Parse self-review output. Malformed output is ``needs_repair``, never pass."""
    data = _extract_json(text)
    if data is None:
        return SelfReviewResult(status="needs_repair", malformed=True)
    status = str(data.get("status", "")).strip().lower()
    if status not in {"pass", "fail", "needs_repair"}:
        status = "needs_repair"
    findings = _normalise_finding_list(
        data.get("findings"), default_severity="non_blocking", source="self",
    )
    # Any blocking self-finding forces at least needs_repair.
    if any(f.is_blocking for f in findings) and status == "pass":
        status = "needs_repair"
    confidence = data.get("confidence")
    try:
        confidence = float(confidence) if confidence is not None else None
    except (TypeError, ValueError):
        confidence = None
    repairs = [str(r) for r in (data.get("recommended_repairs") or []) if isinstance(r, (str, int, float))]
    return SelfReviewResult(
        status=status,
        findings=findings,
        requirements_checked=[str(r) for r in (data.get("requirements_checked") or [])],
        files_reviewed=[str(r) for r in (data.get("files_reviewed") or [])],
        confidence=confidence,
        recommended_repairs=repairs,
    )


def parse_independent_review(text: str) -> IndependentReviewResult:
    """Parse independent-review output. Malformed output is ``needs_repair``.

    A reviewer response is only ever an *approval* when it is well-formed and
    explicitly says ``approve``. Anything unparseable, empty, or ambiguous is a
    non-approval so it can never end a job.
    """
    data = _extract_json(text)
    if data is None:
        return IndependentReviewResult(status="needs_repair", malformed=True)
    status = str(data.get("status", "")).strip().lower()
    if status not in {"approve", "reject", "needs_repair"}:
        status = "needs_repair"
    blocking = _normalise_finding_list(
        data.get("blocking_findings"), default_severity="blocking", source="independent",
    )
    non_blocking = _normalise_finding_list(
        data.get("non_blocking_findings"), default_severity="non_blocking", source="independent",
    )
    if blocking and status == "approve":
        status = "needs_repair"
    # Fail closed: a well-formed but non-approving response with no explicit
    # blocking finding must still surface a blocker, otherwise "reject" with an
    # empty list would silently pass.
    if status in {"reject", "needs_repair"} and not blocking:
        blocking = [ReviewFinding(
            severity="blocking", category="review_not_approved", source="independent",
            message=f"Independent reviewer returned status '{status}' without a blocking finding",
        )]
    insufficient = [str(r) for r in (data.get("requirements_with_insufficient_evidence") or [])]
    reviewed_diff = bool(data.get("reviewed_diff", False))
    return IndependentReviewResult(
        status=status,
        blocking_findings=blocking,
        non_blocking_findings=non_blocking,
        requirements_with_insufficient_evidence=insufficient,
        reviewed_diff=reviewed_diff,
    )


